-- -----------------------------------------------------------------------------

CREATE TABLE CHAMPION (
    CHAMPION_ID        NUMBER PRIMARY KEY,
    CHAMPION_KEY       VARCHAR2(50) NOT NULL,
    CHAMPION_NAME_KR   VARCHAR2(100),
    CHAMPION_NAME_EN   VARCHAR2(100),
    IMAGE_URL          VARCHAR2(500),
    VERSION            VARCHAR2(30),
    UPDATED_AT         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT UK_CHAMPION_KEY UNIQUE (CHAMPION_KEY)
);

COMMENT ON TABLE CHAMPION IS 'Data Dragon 챔피언 정보 캐시 테이블';
COMMENT ON COLUMN CHAMPION.CHAMPION_ID IS 'DDragon 챔피언 id (숫자)';
COMMENT ON COLUMN CHAMPION.CHAMPION_KEY IS 'DDragon 챔피언 key (영문, 예: Ahri)';

CREATE TABLE SUMMONER (
    SUMMONER_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GAME_NAME          VARCHAR2(100) NOT NULL,
    TAG_LINE           VARCHAR2(20) NOT NULL,
    PUUID              VARCHAR2(100),
    RIOT_SUMMONER_ID   VARCHAR2(100),
    ACCOUNT_ID         VARCHAR2(100),
    CREATED_AT         DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT UK_SUMMONER_RIOT_ID UNIQUE (GAME_NAME, TAG_LINE)
);

COMMENT ON TABLE SUMMONER IS '소환사 기본 정보 마스터 테이블';
COMMENT ON COLUMN SUMMONER.SUMMONER_ID IS '소환사 내부 관리 ID';
COMMENT ON COLUMN SUMMONER.GAME_NAME IS 'Riot ID 게임명';
COMMENT ON COLUMN SUMMONER.TAG_LINE IS 'Riot ID 태그';
COMMENT ON COLUMN SUMMONER.PUUID IS 'Riot PUUID';

-- -----------------------------------------------------------------------------
-- 2. 전적 집계 (랭크 fallback · 내전 우선)
-- -----------------------------------------------------------------------------

CREATE TABLE SUMMONER_RANK_STAT (
    RANK_STAT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUMMONER_ID        NUMBER NOT NULL,

    QUEUE_TYPE         VARCHAR2(30) DEFAULT 'RANKED_SOLO_5x5' NOT NULL,

    TIER               VARCHAR2(20),
    RANK_NAME          VARCHAR2(10),
    LEAGUE_POINTS      NUMBER,
    WINS               NUMBER DEFAULT 0,
    LOSSES             NUMBER DEFAULT 0,
    WIN_RATE           NUMBER(5,2),

    MAIN_POSITION      VARCHAR2(20),
    MOST_CHAMPION_1    NUMBER,
    MOST_CHAMPION_2    NUMBER,
    MOST_CHAMPION_3    NUMBER,

    UPDATED_AT         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_SRS_SUMMONER
        FOREIGN KEY (SUMMONER_ID) REFERENCES SUMMONER (SUMMONER_ID),
    CONSTRAINT FK_SRS_MOST1 FOREIGN KEY (MOST_CHAMPION_1) REFERENCES CHAMPION (CHAMPION_ID),
    CONSTRAINT FK_SRS_MOST2 FOREIGN KEY (MOST_CHAMPION_2) REFERENCES CHAMPION (CHAMPION_ID),
    CONSTRAINT FK_SRS_MOST3 FOREIGN KEY (MOST_CHAMPION_3) REFERENCES CHAMPION (CHAMPION_ID),

    CONSTRAINT UK_SRS_SUMMONER_QUEUE UNIQUE (SUMMONER_ID, QUEUE_TYPE)
);

COMMENT ON TABLE SUMMONER_RANK_STAT IS '소환사 랭크 전적 (내전 0판 시 표시용 fallback)';

CREATE TABLE SUMMONER_CUSTOM_STAT (
    CUSTOM_STAT_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUMMONER_ID        NUMBER NOT NULL,

    TOTAL_GAMES        NUMBER DEFAULT 0 NOT NULL,
    WINS               NUMBER DEFAULT 0 NOT NULL,
    LOSSES             NUMBER DEFAULT 0 NOT NULL,
    WIN_RATE           NUMBER(5,2) DEFAULT 0 NOT NULL,

    TOTAL_KILLS        NUMBER DEFAULT 0,
    TOTAL_DEATHS       NUMBER DEFAULT 0,
    TOTAL_ASSISTS      NUMBER DEFAULT 0,

    AVG_KILLS          NUMBER(5,2),
    AVG_DEATHS         NUMBER(5,2),
    AVG_ASSISTS        NUMBER(5,2),
    AVG_KDA            NUMBER(6,2),

    MAIN_POSITION      VARCHAR2(20),
    MOST_CHAMPION_1    NUMBER,
    MOST_CHAMPION_2    NUMBER,
    MOST_CHAMPION_3    NUMBER,

    PLAYER_SCORE       NUMBER DEFAULT 0,
    UPDATED_AT         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_SCS_SUMMONER
        FOREIGN KEY (SUMMONER_ID) REFERENCES SUMMONER (SUMMONER_ID),
    CONSTRAINT FK_SCS_MOST1 FOREIGN KEY (MOST_CHAMPION_1) REFERENCES CHAMPION (CHAMPION_ID),
    CONSTRAINT FK_SCS_MOST2 FOREIGN KEY (MOST_CHAMPION_2) REFERENCES CHAMPION (CHAMPION_ID),
    CONSTRAINT FK_SCS_MOST3 FOREIGN KEY (MOST_CHAMPION_3) REFERENCES CHAMPION (CHAMPION_ID),

    CONSTRAINT UK_SCS_SUMMONER UNIQUE (SUMMONER_ID),

    CONSTRAINT CK_SCS_MAIN_POSITION
        CHECK (MAIN_POSITION IN ('TOP', 'JUNGLE', 'MID', 'ADC', 'SUPPORT') OR MAIN_POSITION IS NULL)
);

COMMENT ON TABLE SUMMONER_CUSTOM_STAT IS '소환사 내전 전체 전적 집계 (내전 1판 이상 시 우선 표시)';
COMMENT ON COLUMN SUMMONER_CUSTOM_STAT.PLAYER_SCORE IS '자동 팀 배치용 누적 점수';
COMMENT ON COLUMN SUMMONER_CUSTOM_STAT.TOTAL_GAMES IS '내전 0이면 소환사 입력 화면에서 랭크 전적 사용';

CREATE TABLE SUMMONER_CUSTOM_POSITION_STAT (
    POSITION_STAT_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUMMONER_ID        NUMBER NOT NULL,

    POSITION_NAME      VARCHAR2(20) NOT NULL,

    TOTAL_GAMES        NUMBER DEFAULT 0 NOT NULL,
    WINS               NUMBER DEFAULT 0 NOT NULL,
    LOSSES             NUMBER DEFAULT 0 NOT NULL,
    WIN_RATE           NUMBER(5,2) DEFAULT 0 NOT NULL,

    TOTAL_KILLS        NUMBER DEFAULT 0,
    TOTAL_DEATHS       NUMBER DEFAULT 0,
    TOTAL_ASSISTS      NUMBER DEFAULT 0,

    AVG_KILLS          NUMBER(5,2),
    AVG_DEATHS         NUMBER(5,2),
    AVG_ASSISTS        NUMBER(5,2),
    AVG_KDA            NUMBER(6,2),

    MOST_CHAMPION_1    NUMBER,
    MOST_CHAMPION_2    NUMBER,
    MOST_CHAMPION_3    NUMBER,

    UPDATED_AT         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_SCPS_SUMMONER
        FOREIGN KEY (SUMMONER_ID) REFERENCES SUMMONER (SUMMONER_ID),
    CONSTRAINT FK_SCPS_MOST1 FOREIGN KEY (MOST_CHAMPION_1) REFERENCES CHAMPION (CHAMPION_ID),
    CONSTRAINT FK_SCPS_MOST2 FOREIGN KEY (MOST_CHAMPION_2) REFERENCES CHAMPION (CHAMPION_ID),
    CONSTRAINT FK_SCPS_MOST3 FOREIGN KEY (MOST_CHAMPION_3) REFERENCES CHAMPION (CHAMPION_ID),

    CONSTRAINT UK_SCPS_SUMMONER_POSITION UNIQUE (SUMMONER_ID, POSITION_NAME),

    CONSTRAINT CK_SCPS_POSITION
        CHECK (POSITION_NAME IN ('TOP', 'JUNGLE', 'MID', 'ADC', 'SUPPORT'))
);

COMMENT ON TABLE SUMMONER_CUSTOM_POSITION_STAT IS '소환사 내전 포지션별 전적 집계';

-- -----------------------------------------------------------------------------
-- 3. 내전 세션 · 경기
-- -----------------------------------------------------------------------------

CREATE TABLE CUSTOM_GAME (
    GAME_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SESSION_CODE       VARCHAR2(64) NOT NULL,

    SERIES_TYPE        VARCHAR2(10) DEFAULT 'SINGLE' NOT NULL,
    PEERLESS_YN        CHAR(1) DEFAULT 'N' NOT NULL,
    STATUS             VARCHAR2(30) DEFAULT 'CREATED' NOT NULL,

    CURRENT_MATCH_NO   NUMBER DEFAULT 1 NOT NULL,
    RED_SERIES_WINS    NUMBER DEFAULT 0 NOT NULL,
    BLUE_SERIES_WINS   NUMBER DEFAULT 0 NOT NULL,

    CREATED_AT         DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT         DATE DEFAULT SYSDATE NOT NULL,
    ENDED_AT           DATE,

    CONSTRAINT UK_CUSTOM_GAME_SESSION UNIQUE (SESSION_CODE),

    CONSTRAINT CK_CG_SERIES_TYPE
        CHECK (SERIES_TYPE IN ('SINGLE', 'BO3', 'BO5', 'UNLIMITED')),
    CONSTRAINT CK_CG_PEERLESS
        CHECK (PEERLESS_YN IN ('Y', 'N')),
    CONSTRAINT CK_CG_STATUS
        CHECK (STATUS IN (
            'CREATED',
            'PLAYERS',
            'TEAM_SETUP',
            'DRAFT',
            'PLAYING',
            'RESULT_INPUT',
            'FINISHED',
            'CANCELLED'
        ))
);

COMMENT ON TABLE CUSTOM_GAME IS '내전 세션 마스터 (프론트 sessionId ↔ SESSION_CODE)';
COMMENT ON COLUMN CUSTOM_GAME.SESSION_CODE IS '클라이언트 세션 UUID';
COMMENT ON COLUMN CUSTOM_GAME.SERIES_TYPE IS 'SINGLE / BO3 / BO5 / UNLIMITED';
COMMENT ON COLUMN CUSTOM_GAME.CURRENT_MATCH_NO IS '시리즈 내 현재 경기 번호';

CREATE TABLE CUSTOM_GAME_PLAYER (
    GAME_PLAYER_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    GAME_ID            NUMBER NOT NULL,
    SUMMONER_ID        NUMBER NOT NULL,

    TEAM_COLOR         VARCHAR2(10),
    POSITION_NAME      VARCHAR2(20),
    IS_CAPTAIN_YN      CHAR(1) DEFAULT 'N' NOT NULL,

    PLAYER_SCORE       NUMBER DEFAULT 0,
    SORT_ORDER         NUMBER,

    CREATED_AT         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_CGP_GAME
        FOREIGN KEY (GAME_ID) REFERENCES CUSTOM_GAME (GAME_ID),
    CONSTRAINT FK_CGP_SUMMONER
        FOREIGN KEY (SUMMONER_ID) REFERENCES SUMMONER (SUMMONER_ID),

    CONSTRAINT UK_CGP_GAME_SUMMONER UNIQUE (GAME_ID, SUMMONER_ID),

    CONSTRAINT CK_CGP_TEAM_COLOR
        CHECK (TEAM_COLOR IN ('RED', 'BLUE') OR TEAM_COLOR IS NULL),
    CONSTRAINT CK_CGP_POSITION
        CHECK (POSITION_NAME IN ('TOP', 'JUNGLE', 'MID', 'ADC', 'SUPPORT') OR POSITION_NAME IS NULL),
    CONSTRAINT CK_CGP_CAPTAIN
        CHECK (IS_CAPTAIN_YN IN ('Y', 'N'))
);

COMMENT ON TABLE CUSTOM_GAME_PLAYER IS '내전 세션 참가자 (10인)';
COMMENT ON COLUMN CUSTOM_GAME_PLAYER.PLAYER_SCORE IS '해당 내전 시작 시점 자동 배치용 점수 스냅샷';

CREATE TABLE CUSTOM_MATCH (
    MATCH_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    GAME_ID            NUMBER NOT NULL,
    MATCH_NO           NUMBER NOT NULL,

    STATUS             VARCHAR2(30) DEFAULT 'CREATED' NOT NULL,
    WIN_TEAM_COLOR     VARCHAR2(10),

    CURRENT_TURN_NO    NUMBER DEFAULT 1 NOT NULL,

    CREATED_AT         DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT         DATE DEFAULT SYSDATE NOT NULL,
    ENDED_AT           DATE,

    CONSTRAINT FK_CM_GAME
        FOREIGN KEY (GAME_ID) REFERENCES CUSTOM_GAME (GAME_ID),

    CONSTRAINT UK_CM_GAME_MATCH_NO UNIQUE (GAME_ID, MATCH_NO),

    CONSTRAINT CK_CM_STATUS
        CHECK (STATUS IN (
            'CREATED',
            'PICK_BAN',
            'PLAYING',
            'RESULT_INPUT',
            'FINISHED'
        )),
    CONSTRAINT CK_CM_WIN_TEAM
        CHECK (WIN_TEAM_COLOR IN ('RED', 'BLUE') OR WIN_TEAM_COLOR IS NULL)
);

COMMENT ON TABLE CUSTOM_MATCH IS '내전 경기 단위 (단판 1건, BO3/BO5는 MATCH_NO 증가)';

CREATE TABLE CUSTOM_PICK_BAN (
    PICK_BAN_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    MATCH_ID           NUMBER NOT NULL,

    TURN_NO            NUMBER NOT NULL,
    TEAM_COLOR         VARCHAR2(10) NOT NULL,
    ACTION_TYPE        VARCHAR2(10) NOT NULL,

    CHAMPION_ID        NUMBER NOT NULL,
    SUMMONER_ID        NUMBER,

    CREATED_AT         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_CPB_MATCH
        FOREIGN KEY (MATCH_ID) REFERENCES CUSTOM_MATCH (MATCH_ID),
    CONSTRAINT FK_CPB_SUMMONER
        FOREIGN KEY (SUMMONER_ID) REFERENCES SUMMONER (SUMMONER_ID),
    CONSTRAINT FK_CPB_CHAMPION
        FOREIGN KEY (CHAMPION_ID) REFERENCES CHAMPION (CHAMPION_ID),

    CONSTRAINT UK_CPB_MATCH_TURN UNIQUE (MATCH_ID, TURN_NO),

    CONSTRAINT CK_CPB_TEAM
        CHECK (TEAM_COLOR IN ('RED', 'BLUE')),
    CONSTRAINT CK_CPB_ACTION
        CHECK (ACTION_TYPE IN ('BAN', 'PICK'))
);

COMMENT ON TABLE CUSTOM_PICK_BAN IS '경기별 밴픽 진행 기록';
COMMENT ON COLUMN CUSTOM_PICK_BAN.SUMMONER_ID IS 'PICK 시 필수, BAN 시 NULL';

CREATE TABLE CUSTOM_MATCH_PLAYER_RESULT (
    RESULT_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    MATCH_ID           NUMBER NOT NULL,
    SUMMONER_ID        NUMBER NOT NULL,

    TEAM_COLOR         VARCHAR2(10) NOT NULL,
    POSITION_NAME      VARCHAR2(20),
    CHAMPION_ID        NUMBER,

    WIN_YN             CHAR(1) NOT NULL,

    KILLS              NUMBER,
    DEATHS             NUMBER,
    ASSISTS            NUMBER,

    DAMAGE             NUMBER,
    CS                 NUMBER,
    NOTE               VARCHAR2(500),

    CREATED_AT         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_CMPR_MATCH
        FOREIGN KEY (MATCH_ID) REFERENCES CUSTOM_MATCH (MATCH_ID),
    CONSTRAINT FK_CMPR_SUMMONER
        FOREIGN KEY (SUMMONER_ID) REFERENCES SUMMONER (SUMMONER_ID),
    CONSTRAINT FK_CMPR_CHAMPION
        FOREIGN KEY (CHAMPION_ID) REFERENCES CHAMPION (CHAMPION_ID),

    CONSTRAINT UK_CMPR_MATCH_SUMMONER UNIQUE (MATCH_ID, SUMMONER_ID),

    CONSTRAINT CK_CMPR_TEAM
        CHECK (TEAM_COLOR IN ('RED', 'BLUE')),
    CONSTRAINT CK_CMPR_POSITION
        CHECK (POSITION_NAME IN ('TOP', 'JUNGLE', 'MID', 'ADC', 'SUPPORT') OR POSITION_NAME IS NULL),
    CONSTRAINT CK_CMPR_WIN
        CHECK (WIN_YN IN ('Y', 'N'))
);

COMMENT ON TABLE CUSTOM_MATCH_PLAYER_RESULT IS '경기별 플레이어 결과 (KDA 등)';

-- -----------------------------------------------------------------------------
-- 4. 인덱스 (UK와 중복되는 단일 컬럼 인덱스는 제외)
-- -----------------------------------------------------------------------------

CREATE INDEX IDX_CGP_GAME_ID ON CUSTOM_GAME_PLAYER (GAME_ID);
CREATE INDEX IDX_CGP_SUMMONER_ID ON CUSTOM_GAME_PLAYER (SUMMONER_ID);

CREATE INDEX IDX_CM_GAME_ID ON CUSTOM_MATCH (GAME_ID);

CREATE INDEX IDX_CPB_MATCH_ID ON CUSTOM_PICK_BAN (MATCH_ID);
CREATE INDEX IDX_CPB_CHAMPION_ID ON CUSTOM_PICK_BAN (CHAMPION_ID);

CREATE INDEX IDX_CMPR_MATCH_ID ON CUSTOM_MATCH_PLAYER_RESULT (MATCH_ID);
CREATE INDEX IDX_CMPR_SUMMONER_ID ON CUSTOM_MATCH_PLAYER_RESULT (SUMMONER_ID);
CREATE INDEX IDX_CMPR_CHAMPION_ID ON CUSTOM_MATCH_PLAYER_RESULT (CHAMPION_ID);

